function state = find_state(chart, stateName)
state = chart.find('-isa', 'Stateflow.State', 'Name', stateName);
assert(~isempty(state), 'Cannot find Stateflow state %s.', stateName);
state = state(1);
end

function reset_recovery_counter(root, chartPath, counterName)
chart = root.find('-isa', 'Stateflow.Chart', 'Path', chartPath);
assert(~isempty(chart), 'Cannot find chart %s.', chartPath);
transitions = chart.find('-isa', 'Stateflow.Transition');
for index = 1:numel(transitions)
    item = transitions(index);
    if isa(item.Source, 'Stateflow.State') && ...
            isa(item.Destination, 'Stateflow.State') && ...
            strcmp(item.Source.Name, 'judge') && ...
            strcmp(item.Destination.Name, 'compare')
        item.LabelString = sprintf('[hasChanged(%s)]{%s=0}', ...
            input_name_for_counter(counterName), counterName);
        return;
    end
end
error('Cannot find judge-to-compare recovery transition in %s.', chartPath);
end

function name = input_name_for_counter(counterName)
if strcmp(counterName, 'hbcnt')
    name = 'res_heartbeat';
else
    name = 'lifesig';
end
end

function update_assi_chart(root, chartPath, signalName)
chart = root.find('-isa', 'Stateflow.Chart', 'Path', chartPath);
assert(~isempty(chart), 'Cannot find ASSI chart %s.', chartPath);
transitions = chart.find('-isa', 'Stateflow.Transition');
for index = 1:numel(transitions)
    item = transitions(index);
    if ~isa(item.Destination, 'Stateflow.State')
        continue;
    end
    destination = item.Destination.Name;
    if strcmp(destination, 'Blink')
        item.LabelString = sprintf('[%s==2]', signalName);
    elseif strcmp(destination, 'On')
        item.LabelString = sprintf('[%s==1]', signalName);
    elseif strcmp(destination, 'Close')
        item.LabelString = sprintf('[%s==0]', signalName);
    end
end
end

