if getSimulinkBlockHandle(lockNotTs) == -1
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        lockNotTs, 'Operator', 'NOT', 'Inputs', '1', ...
        'Position', [835 450 880 485]);
end
