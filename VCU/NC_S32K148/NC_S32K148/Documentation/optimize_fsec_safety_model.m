    add_block('simulink/Signal Routing/Data Store Read', emergencyReadTs, ...
        'DataStoreName', 'as_emergency_flag', ...
        'Position', [690 500 805 525]);
end
emergencyNotTs = [tsSystem '/No_AS_Emergency'];
if getSimulinkBlockHandle(emergencyNotTs) == -1
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        emergencyNotTs, 'Operator', 'NOT', 'Inputs', '1', ...
        'Position', [835 495 880 530]);
end
tsGate = [tsSystem '/TS_Safety_Gate'];
if getSimulinkBlockHandle(tsGate) == -1
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        tsGate, 'Operator', 'AND', 'Inputs', '3', ...
        'Position', [910 385 960 430]);
end
set_param(tsGate, 'Inputs', '3');
delete_input_line(lockNotTs, 1);
delete_input_line(emergencyNotTs, 1);
clear_all_input_lines(tsGate);
delete_input_line([tsSystem '/ts'], 1);
add_line(tsSystem, 'FSEC_Safety_Lock_Read/1', ...
    'No_FSEC_Safety_Lock/1', 'autorouting', 'on');
add_line(tsSystem, 'Chart2/1', 'TS_Safety_Gate/1', 'autorouting', 'on');
add_line(tsSystem, 'No_FSEC_Safety_Lock/1', ...
    'TS_Safety_Gate/2', 'autorouting', 'on');
add_line(tsSystem, 'AS_Emergency_Read/1', ...
    'No_AS_Emergency/1', 'autorouting', 'on');
add_line(tsSystem, 'No_AS_Emergency/1', ...
    'TS_Safety_Gate/3', 'autorouting', 'on');
add_line(tsSystem, 'TS_Safety_Gate/1', 'ts/1', 'autorouting', 'on');
