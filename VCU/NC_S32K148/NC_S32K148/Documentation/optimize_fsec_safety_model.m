function optimize_fsec_safety_model()
%OPTIMIZE_FSEC_SAFETY_MODEL Add preliminary FSEC safety diagnostics.
% Root model I/O, the function-call schedule and the hand-written software
% architecture are preserved. The vehicle netlist remains the authority for
% physical signal assignment.

modelDir = 'C:\Users\icemi\Desktop\RZS_Repository\VCU\Models\DBC_Debug';
model = 'VCU10';
modelFile = fullfile(modelDir, [model '.slx']);
dictionaryFile = fullfile(modelDir, 'VCU10DB.sldd');
backupDir = fullfile(modelDir, 'Backup_20260729_before_fsec_safety');

if ~exist(backupDir, 'dir')
    mkdir(backupDir);
    copyfile(modelFile, fullfile(backupDir, [model '.slx']));
    copyfile(dictionaryFile, fullfile(backupDir, 'VCU10DB.sldd'));
end

oldDir = pwd;
cleanupDir = onCleanup(@() cd(oldDir));
cd(modelDir);
load_system(model);
cleanupModel = onCleanup(@() close_system(model, 0));
root = sfroot;

%% Retain raw pressure voltages in the existing sensor bus.
sensorSystem = [model '/Sensor_Signal'];
sensorBus = [sensorSystem '/Bus Creator'];
set_param(sensorBus, 'Inputs', '12');
replace_input_line(sensorBus, 11, sensorSystem, ...
    'airprs_sensor1/1', 'Bus Creator/11', 'airprs1_raw');
replace_input_line(sensorBus, 12, sensorSystem, ...
    'airprs_sensor2/1', 'Bus Creator/12', 'airprs2_raw');

ensure_annotation(sensorSystem, ...
    ['FSEC diagnostics: brkps_raw is checked against 0.10-4.90 V. ' ...
     'Air pressure sensor 1 is the reservoir/ready side; sensor 2 is ' ...
     'the solenoid downstream/cylinder side.'], ...
    [170 55 980 100]);

%% Add debounced brake, pressure-plausibility and communication diagnostics.
asbSystem = [model '/ASB_Selfcheck'];
asbSelector = [asbSystem '/Bus Selector'];
set_param(asbSelector, 'OutputSignals', ...
    ['airprs_sensor1,brkps_raw,airprs1_raw,airprs2_raw,' ...
     'airprs_sensor2']);

monitorBlock = [asbSystem '/FSEC_Sensor_Monitor'];
if getSimulinkBlockHandle(monitorBlock) == -1
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
        monitorBlock, 'Position', [560 390 760 535]);
end
monitorChart = find_em_chart(root, monitorBlock);
monitorChart.Script = sensor_monitor_script();

% The MATLAB Function ports are rebuilt immediately after setting Script.
set_param(model, 'SimulationCommand', 'update');
clear_all_input_lines(monitorBlock);
add_line(asbSystem, 'Bus Selector/2', 'FSEC_Sensor_Monitor/1', ...
    'autorouting', 'on');
add_line(asbSystem, 'Bus Selector/3', 'FSEC_Sensor_Monitor/2', ...
    'autorouting', 'on');
add_line(asbSystem, 'Bus Selector/4', 'FSEC_Sensor_Monitor/3', ...
    'autorouting', 'on');
add_line(asbSystem, 'Bus Selector/1', 'FSEC_Sensor_Monitor/4', ...
    'autorouting', 'on');
add_line(asbSystem, 'Bus Selector/5', 'FSEC_Sensor_Monitor/5', ...
    'autorouting', 'on');
add_line(asbSystem, 'brkmotor_check/1', 'FSEC_Sensor_Monitor/6', ...
    'autorouting', 'on');
add_line(asbSystem, 'Bus Selector1/1', 'FSEC_Sensor_Monitor/7', ...
    'autorouting', 'on');
add_line(asbSystem, 'ebs_drivercheck/1', 'FSEC_Sensor_Monitor/8', ...
    'autorouting', 'on');

brakeGate = [asbSystem '/Brake_On_Valid_Gate'];
if getSimulinkBlockHandle(brakeGate) == -1
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        brakeGate, 'Operator', 'AND', 'Inputs', '2', ...
        'Position', [835 275 885 320]);
end
clear_all_input_lines(brakeGate);
delete_input_line([asbSystem '/brake_on'], 1);
add_line(asbSystem, 'Brake_Sensor_Check/2', 'Brake_On_Valid_Gate/1', ...
    'autorouting', 'on');
add_line(asbSystem, 'FSEC_Sensor_Monitor/1', 'Brake_On_Valid_Gate/2', ...
    'autorouting', 'on');
add_line(asbSystem, 'Brake_On_Valid_Gate/1', 'brake_on/1', ...
    'autorouting', 'on');

safetyNot = [asbSystem '/No_FSEC_Safety_Fault'];
if getSimulinkBlockHandle(safetyNot) == -1
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        safetyNot, 'Operator', 'NOT', 'Inputs', '1', ...
        'Position', [795 430 840 460]);
end
delete_input_line(safetyNot, 1);
set_param([asbSystem '/Logical Operator'], 'Inputs', '5');
delete_input_line([asbSystem '/Logical Operator'], 5);
add_line(asbSystem, 'FSEC_Sensor_Monitor/2', ...
    'No_FSEC_Safety_Fault/1', 'autorouting', 'on');
add_line(asbSystem, 'No_FSEC_Safety_Fault/1', ...
    'Logical Operator/5', 'autorouting', 'on');

safetyOut = [asbSystem '/safety_fault'];
if getSimulinkBlockHandle(safetyOut) == -1
    add_block('simulink/Sinks/Out1', safetyOut, 'Port', '3', ...
        'Position', [915 440 945 460]);
end
delete_input_line(safetyOut, 1);
add_line(asbSystem, 'FSEC_Sensor_Monitor/2', 'safety_fault/1', ...
    'autorouting', 'on');

