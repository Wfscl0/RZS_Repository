function ensure_inport(system, name, port, position)
path = [system '/' name];
if getSimulinkBlockHandle(path) == -1
    add_block('simulink/Sources/In1', path, 'Port', num2str(port), ...
        'OutDataTypeStr', 'boolean', 'Position', position);
else
    set_param(path, 'Port', num2str(port));
end
end

function set_dictionary_parameter(dictionaryFile, name, value, unit, description)
dictionary = Simulink.data.dictionary.open(dictionaryFile);
section = getSection(dictionary, 'Design Data');
parameter = Simulink.Parameter;
parameter.Value = value;
parameter.DataType = 'double';
parameter.Unit = unit;
parameter.Description = description;
try
    entry = getEntry(section, name);
    setValue(entry, parameter);
catch
    addEntry(section, name, parameter);
end
saveChanges(dictionary);
end

