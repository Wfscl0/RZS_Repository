     'EBS_Driver retains its independent hardware diagnostics.'], ...
    [360 15 1040 65]);

%% Feed the combined fault into the AS state machine without changing root I/O.
faultOr = [model '/FSEC_Safety_Fault_OR'];
if getSimulinkBlockHandle(faultOr) == -1
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        faultOr, 'Operator', 'OR', 'Inputs', '2', ...
        'Position', [915 965 970 1010]);
end
clear_all_input_lines(faultOr);
add_line(model, 'ASB_Selfcheck/3', 'FSEC_Safety_Fault_OR/1', ...
    'autorouting', 'on');
add_line(model, 'EBS/5', 'FSEC_Safety_Fault_OR/2', ...
    'autorouting', 'on');

faultDelayRoot = [model '/FSEC_Safety_Fault_Delay'];
if getSimulinkBlockHandle(faultDelayRoot) == -1
    add_block('simulink/Discrete/Unit Delay', faultDelayRoot, ...
        'InitialCondition', 'false', 'SampleTime', '0.01', ...
        'Position', [995 970 1045 1005]);
end
delete_input_line(faultDelayRoot, 1);
add_line(model, 'FSEC_Safety_Fault_OR/1', ...
    'FSEC_Safety_Fault_Delay/1', 'autorouting', 'on');

asSystem = [model '/AS_Stateflow'];
safetyIn = [asSystem '/safety_fault'];
if getSimulinkBlockHandle(safetyIn) == -1
    add_block('simulink/Sources/In1', safetyIn, 'Port', '14', ...
        'OutDataTypeStr', 'boolean', 'Position', [30 690 60 710]);
end

asChart = root.find('-isa', 'Stateflow.Chart', ...
    'Path', [asSystem '/Chart']);
safetyData = find_chart_data(asChart, 'safety_fault');
if isempty(safetyData)
    safetyData = Stateflow.Data(asChart);
    safetyData.Name = 'safety_fault';
    safetyData.Scope = 'Input';
    safetyData.Port = 14;
    set_boolean_type(safetyData);
end

lockData = find_chart_data(asChart, 'safety_lock');
if isempty(lockData)
    lockData = Stateflow.Data(asChart);
    lockData.Name = 'safety_lock';
    lockData.Scope = 'Output';
    lockData.Port = 7;
    lockData.Props.InitialValue = '0';
    lockData.Props.Type.Method = 'Built-in';
    lockData.Props.Type.Primitive = 'double';
end

% Rebuild chart ports after adding Stateflow data.
set_param(model, 'SimulationCommand', 'update');
delete_input_line([asSystem '/Chart'], 14);
add_line(asSystem, 'safety_fault/1', 'Chart/14', 'autorouting', 'on');

lockOut = [asSystem '/safety_lock'];
if getSimulinkBlockHandle(lockOut) == -1
    add_block('simulink/Sinks/Out1', lockOut, 'Port', '7', ...
        'OutDataTypeStr', 'double', 'Position', [985 575 1015 595]);
end
delete_input_line(lockOut, 1);
add_line(asSystem, 'Chart/7', 'safety_lock/1', 'autorouting', 'on');

emergencyState = asChart.find('-isa', 'Stateflow.State', ...
    'Name', 'AS_Emergency');
if ~contains(emergencyState.LabelString, 'safety_lock=1')
    emergencyState.LabelString = sprintf('%s\nsafety_lock=1;', ...
        emergencyState.LabelString);
end

update_as_transitions(asChart);

delete_input_line([model '/AS_Stateflow'], 14);
add_line(model, 'FSEC_Safety_Fault_Delay/1', 'AS_Stateflow/14', ...
    'autorouting', 'on');

lockMemory = [model '/FSEC_Safety_Lock_Memory'];
if getSimulinkBlockHandle(lockMemory) == -1
    add_block('simulink/Signal Routing/Data Store Memory', lockMemory, ...
        'DataStoreName', 'safety_lock', 'InitialValue', '0', ...
        'OutDataTypeStr', 'double', 'Position', [1025 960 1155 995]);
end
lockWrite = [model '/FSEC_Safety_Lock_Write'];
if getSimulinkBlockHandle(lockWrite) == -1
    add_block('simulink/Signal Routing/Data Store Write', lockWrite, ...
        'DataStoreName', 'safety_lock', 'Position', [1185 960 1285 990]);
end
delete_input_line(lockWrite, 1);
add_line(model, 'AS_Stateflow/7', 'FSEC_Safety_Lock_Write/1', ...
    'autorouting', 'on');

%% A software emergency lock forces TS off in the same model step.
tsSystem = [model '/TS_Activation'];
