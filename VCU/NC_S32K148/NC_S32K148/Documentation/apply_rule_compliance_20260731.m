function chart = find_em_chart(root, blockPath)
charts = root.find('-isa', 'Stateflow.EMChart');
chart = [];
for index = 1:numel(charts)
    fullPath = [charts(index).Path '/' charts(index).Name];
    if strcmp(charts(index).Path, blockPath) || strcmp(fullPath, blockPath)
        chart = charts(index);
        break;
    end
end
if isempty(chart)
    error('MATLAB Function chart not found for %s.', blockPath);
end
end

function delete_input_line(block, portNumber)
handles = get_param(block, 'LineHandles');
if isfield(handles, 'Inport') && portNumber <= numel(handles.Inport) && ...
        handles.Inport(portNumber) ~= -1
    delete_line(handles.Inport(portNumber));
end
end

function clear_all_input_lines(block)
handles = get_param(block, 'LineHandles');
if ~isfield(handles, 'Inport')
    return;
end
for index = 1:numel(handles.Inport)
    if handles.Inport(index) ~= -1
        delete_line(handles.Inport(index));
    end
end
end

function ensure_annotation(system, text, position)
annotations = find_system(system, 'FindAll', 'on', 'SearchDepth', 1, ...
    'Type', 'annotation');
for index = 1:numel(annotations)
    if strcmp(get_param(annotations(index), 'PlainText'), text)
        return;
    end
end
annotation = Simulink.Annotation(system, text);
annotation.Position = position;
end
