if getSimulinkBlockHandle(ebsFaultOut) == -1
    add_block('simulink/Sinks/Out1', ebsFaultOut, 'Port', '5', ...
        'Position', [885 365 915 385]);
end
delete_input_line(ebsFaultOut, 1);
add_line(ebsSystem, 'EBS_Sensor_Fault_Delay/1', ...
    'ebs_sensor_fault/1', 'autorouting', 'on');

ensure_annotation(ebsSystem, ...
    ['EBS response check: after a trigger with available reservoir pressure, ' ...
