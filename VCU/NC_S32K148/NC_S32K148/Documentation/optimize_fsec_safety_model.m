end

function text = sensor_monitor_script()
text = sprintf([ ...
    'function [brake_sensor_valid, safety_fault, brake_sensor_fault, air_sensor_fault] = fsec_sensor_monitor(brake_raw_mv, air_ready_raw_mv, air_work_raw_mv, air_ready_bar, air_work_bar, esp_ok, res_ok, ebs_driver_ok)\n' ...
    '%%#codegen\n' ...
    '%% Wide electrical thresholds avoid nuisance trips before final calibration.\n' ...
    'persistent brake_bad brake_good air_bad air_good comm_bad comm_good brake_fault air_fault comm_fault\n' ...
    'if isempty(brake_bad)\n' ...
    '    brake_bad=uint16(0); brake_good=uint16(0); air_bad=uint16(0); air_good=uint16(0);\n' ...
    '    comm_bad=uint16(0); comm_good=uint16(0); brake_fault=false; air_fault=false; comm_fault=false;\n' ...
    'end\n' ...
    'brake_now = (brake_raw_mv < 100.0) || (brake_raw_mv > 4900.0);\n' ...
    'if brake_now\n' ...
    '    brake_good=uint16(0); if brake_bad<uint16(1000), brake_bad=brake_bad+uint16(1); end\n' ...
    '    if brake_bad>=uint16(10), brake_fault=true; end\n' ...
    'else\n' ...
    '    brake_bad=uint16(0); if brake_good<uint16(1000), brake_good=brake_good+uint16(1); end\n' ...
    '    if brake_good>=uint16(50), brake_fault=false; end\n' ...
    'end\n' ...
    '%% 0 V and 10 V are valid endpoints for the 0-10 V air sensors.\n' ...
    '%% Therefore software uses overscale, low reservoir and pair plausibility.\n' ...
    'air_now = (air_ready_raw_mv > 10050.0) || (air_work_raw_mv > 10050.0) || ...\n' ...
    '          (air_ready_bar < 2.5) || (air_work_bar > air_ready_bar + 1.5);\n' ...
    'if air_now\n' ...
    '    air_good=uint16(0); if air_bad<uint16(1000), air_bad=air_bad+uint16(1); end\n' ...
    '    if air_bad>=uint16(50), air_fault=true; end\n' ...
    'else\n' ...
    '    air_bad=uint16(0); if air_good<uint16(1000), air_good=air_good+uint16(1); end\n' ...
    '    if air_good>=uint16(50), air_fault=false; end\n' ...
    'end\n' ...
    'comm_now = (~logical(esp_ok)) || (~logical(res_ok)) || (~logical(ebs_driver_ok));\n' ...
    'if comm_now\n' ...
    '    comm_good=uint16(0); if comm_bad<uint16(1000), comm_bad=comm_bad+uint16(1); end\n' ...
    '    if comm_bad>=uint16(30), comm_fault=true; end\n' ...
    'else\n' ...
    '    comm_bad=uint16(0); if comm_good<uint16(1000), comm_good=comm_good+uint16(1); end\n' ...
    '    if comm_good>=uint16(50), comm_fault=false; end\n' ...
    'end\n' ...
    '%% R2D permission is removed immediately; fault indication remains debounced.\n' ...
    'brake_sensor_valid = (~brake_fault) && (~brake_now);\n' ...
    'brake_sensor_fault = brake_fault;\n' ...
    'air_sensor_fault = air_fault;\n' ...
    'safety_fault = brake_fault || air_fault || comm_fault;\n' ...
    'end\n']);
end

function text = ebs_monitor_script()
text = sprintf([ ...
    'function ebs_sensor_fault = ebs_response_monitor(trigger, asms, driver_ok, air_ready_bar, air_work_bar)\n' ...
    '%%#codegen\n' ...
    '%% EBS_Driver handles electrical faults; VCU verifies pneumatic response.\n' ...
    'persistent last_trigger waiting wait_count relation_count clear_count fault_latched\n' ...
    'if isempty(last_trigger)\n' ...
    '    last_trigger=false; waiting=false; wait_count=uint16(0); relation_count=uint16(0);\n' ...
    '    clear_count=uint16(0); fault_latched=false;\n' ...
    'end\n' ...
    'rising = logical(trigger) && ~last_trigger; last_trigger=logical(trigger);\n' ...
    'if rising && logical(driver_ok) && (air_ready_bar >= 2.5) && (air_work_bar < 1.0)\n' ...
    '    waiting=true; wait_count=uint16(0);\n' ...
    'end\n' ...
    'if waiting\n' ...
    '    if air_work_bar >= 1.0\n' ...
    '        waiting=false; wait_count=uint16(0);\n' ...
    '    else\n' ...
    '        if wait_count<uint16(1000), wait_count=wait_count+uint16(1); end\n' ...
    '        if wait_count>=uint16(50), fault_latched=true; waiting=false; end\n' ...
    '    end\n' ...
    'end\n' ...
    'if air_work_bar > air_ready_bar + 1.5\n' ...
    '    if relation_count<uint16(1000), relation_count=relation_count+uint16(1); end\n' ...
    '    if relation_count>=uint16(20), fault_latched=true; end\n' ...
    'else\n' ...
    '    relation_count=uint16(0);\n' ...
    'end\n' ...
    '%% Recovery is deliberately slow and only allowed outside autonomous mode.\n' ...
    'if (~logical(asms)) && logical(driver_ok) && (air_work_bar < 1.0) && (air_ready_bar >= 2.5)\n' ...
    '    if clear_count<uint16(1000), clear_count=clear_count+uint16(1); end\n' ...
    '    if clear_count>=uint16(100), fault_latched=false; end\n' ...
    'else\n' ...
    '    clear_count=uint16(0);\n' ...
    'end\n' ...
    'ebs_sensor_fault = fault_latched;\n' ...
    'end\n']);
end

function update_as_transitions(chart)
transitions = chart.find('-isa', 'Stateflow.Transition');
for index = 1:numel(transitions)
    transition = transitions(index);
    label = strtrim(transition.LabelString);
    sourceName = object_name(transition.Source);
    destinationName = object_name(transition.Destination);

    if strcmp(destinationName, 'AS_Emergency') && ...
            strcmp(label, '[ebs_working==1]')
        transition.LabelString = ...
            '[ebs_working==1||safety_fault==1||asms_button==0||res_stop==1]';
    elseif strcmp(sourceName, 'AS_Driving') && ...
            strcmp(destinationName, 'AS_Finished') && ...
            contains(label, 'car_spdzero')
        transition.LabelString = ...
            ['[car_spdzero==1&&task_finish==1&&safety_fault==0&&' ...
             'asms_button==1&&res_stop==0]{as_ebs_trig=1}'];
    elseif contains(label, 'after(27,sec)')
        transition.LabelString = ...
            ['after(27,sec)[safety_fault==0&&asms_button==1&&' ...
             'res_stop==0]{as_ebs_trig=1}'];
    elseif strcmp(destinationName, 'AS_Driving') && contains(label, 'res_go')
        transition.LabelString = ...
            ['[res_go==1&&safety_fault==0&&asms_button==1&&' ...
             'res_stop==0]{r2d_warning=T;steer_return=T}'];
    elseif strcmp(destinationName, 'AS_Ready') && contains(label, 'asb_check')
        transition.LabelString = ...
            '[asb_check==1&&safety_fault==0&&safety_lock==0]';
    elseif strcmp(sourceName, 'AS_Off') && ...
            strcmp(destinationName, 'transition')
        transition.LabelString = ...
            ['[as_task==1&&asms_button==1&&safety_fault==0&&' ...
             'safety_lock==0]{brake_flag=2}'];
    elseif strcmp(sourceName, 'AS_Off') && contains(label, 'ami_manualdriving')
        transition.LabelString = ...
            '[ami_manualdriving==1&&safety_fault==0&&safety_lock==0]';
    end
end
end

function name = object_name(object)
if isempty(object)
    name = '';
elseif isa(object, 'Stateflow.State')
    name = object.Name;
else
    name = '';
end
end

function data = find_chart_data(chart, name)
data = chart.find('-isa', 'Stateflow.Data', 'Name', name);
if numel(data) > 1
    data = data(1);
end
end

function set_boolean_type(data)
data.Props.Type.Method = 'Built-in';
data.Props.Type.Primitive = 'boolean';
end

function chart = find_em_chart(root, blockPath)
charts = root.find('-isa', 'Stateflow.EMChart');
chart = [];
for index = 1:numel(charts)
    fullPath = [charts(index).Path '/' charts(index).Name];
    if strcmp(charts(index).Path, blockPath) || strcmp(fullPath, blockPath)
        chart = charts(index);
        break;
    end
end
if isempty(chart)
    error('MATLAB Function chart not found for %s.', blockPath);
end
end

function replace_input_line(block, portNumber, system, source, destination, name)
delete_input_line(block, portNumber);
line = add_line(system, source, destination, 'autorouting', 'on');
set_param(line, 'Name', name);
end

function delete_input_line(block, portNumber)
handles = get_param(block, 'LineHandles');
if portNumber <= numel(handles.Inport) && handles.Inport(portNumber) ~= -1
    delete_line(handles.Inport(portNumber));
end
end

function clear_all_input_lines(block)
handles = get_param(block, 'LineHandles');
for index = 1:numel(handles.Inport)
    if handles.Inport(index) ~= -1
        delete_line(handles.Inport(index));
    end
end
end

function ensure_annotation(system, text, position)
annotations = find_system(system, 'FindAll', 'on', 'SearchDepth', 1, ...
    'Type', 'annotation');
for index = 1:numel(annotations)
    if strcmp(get_param(annotations(index), 'PlainText'), text)
        return;
    end
end
annotation = Simulink.Annotation(system, text);
annotation.Position = position;
end
