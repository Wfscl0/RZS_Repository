function text = eps_monitor_script()
text = sprintf([ ...
    'function eps_safety_fault = eps_scs_monitor(msg1, msg2)\n' ...
    '%%#codegen\n' ...
    '%% 0x401: Byte7 = XOR(Byte0..Byte6); 0x402: Byte1 为发送计数。\n' ...
    'persistent last_counter seen_count stale_count bad_count good_count fault\n' ...
    'if isempty(last_counter)\n' ...
    '    last_counter=msg2(2); seen_count=uint16(0); stale_count=uint16(0);\n' ...
    '    bad_count=uint16(0); good_count=uint16(0); fault=true;\n' ...
    'end\n' ...
    'counter=msg2(2);\n' ...
    'if counter~=last_counter\n' ...
    '    last_counter=counter; stale_count=uint16(0);\n' ...
    '    if seen_count<uint16(1000), seen_count=seen_count+uint16(1); end\n' ...
    'else\n' ...
    '    if stale_count<uint16(1000), stale_count=stale_count+uint16(1); end\n' ...
    'end\n' ...
    'checksum=uint8(0);\n' ...
    'for k=1:7\n' ...
    '    checksum=bitxor(checksum,msg1(k));\n' ...
    'end\n' ...
    'content_valid=(checksum==msg1(8)) && (msg1(3)==uint8(0)) && (msg1(7)==uint8(0));\n' ...
    'fresh=(seen_count>=uint16(3)) && (stale_count<uint16(30));\n' ...
    'valid_now=content_valid && fresh;\n' ...
    'if valid_now\n' ...
    '    bad_count=uint16(0); if good_count<uint16(1000), good_count=good_count+uint16(1); end\n' ...
    '    if good_count>=uint16(50), fault=false; end\n' ...
    'else\n' ...
    '    good_count=uint16(0); if bad_count<uint16(1000), bad_count=bad_count+uint16(1); end\n' ...
    '    if (bad_count>=uint16(3)) || (stale_count>=uint16(30)), fault=true; end\n' ...
    'end\n' ...
    'eps_safety_fault=fault;\n' ...
    'end\n']);
end

