ensure_annotation(model, ...
    ['FSEC preliminary safety layer (2026-07-29): debounced sensor faults, ' ...
     'EBS response diagnostics, Emergency lock, TS shutdown and post-R2D ' ...
     'torque permission. Root interfaces are unchanged.'], ...
    [760 20 1570 70]);

set_param(model, 'SimulationCommand', 'update');
