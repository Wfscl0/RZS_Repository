airFaultTerminator = [asbSystem '/Air_Fault_Class_Terminator'];
if getSimulinkBlockHandle(brakeFaultTerminator) == -1
    add_block('simulink/Sinks/Terminator', brakeFaultTerminator, ...
        'Position', [805 500 825 520]);
end
if getSimulinkBlockHandle(airFaultTerminator) == -1
    add_block('simulink/Sinks/Terminator', airFaultTerminator, ...
        'Position', [805 535 825 555]);
end
delete_input_line(brakeFaultTerminator, 1);
delete_input_line(airFaultTerminator, 1);
add_line(asbSystem, 'FSEC_Sensor_Monitor/3', ...
    'Brake_Fault_Class_Terminator/1', 'autorouting', 'on');
add_line(asbSystem, 'FSEC_Sensor_Monitor/4', ...
    'Air_Fault_Class_Terminator/1', 'autorouting', 'on');

ensure_annotation(asbSystem, ...
    ['Brake sensor open/short confirmation = 100 ms; recovery = 500 ms. ' ...
     'ESP/RES/EBS_Driver fault confirmation = 300 ms. Hydraulic brake ' ...
     'pressure still comes from ESP_T_03.'], ...
    [460 15 1050 65]);

%% Correct the EBS working-side sensor and add pneumatic response checking.
ebsSystem = [model '/EBS'];
workingCompare = [ebsSystem '/Compare To Constant'];
delete_input_line(workingCompare, 1);
add_line(ebsSystem, 'Bus Selector1/2', 'Compare To Constant/1', ...
    'autorouting', 'on');

ebsMonitor = [ebsSystem '/EBS_Response_Monitor'];
if getSimulinkBlockHandle(ebsMonitor) == -1
    add_block('simulink/User-Defined Functions/MATLAB Function', ...
        ebsMonitor, 'Position', [555 325 745 445]);
end
ebsMonitorChart = find_em_chart(root, ebsMonitor);
ebsMonitorChart.Script = ebs_monitor_script();
set_param(model, 'SimulationCommand', 'update');
clear_all_input_lines(ebsMonitor);
add_line(ebsSystem, 'Logical Operator/1', 'EBS_Response_Monitor/1', ...
    'autorouting', 'on');
add_line(ebsSystem, 'Bus Selector/1', 'EBS_Response_Monitor/2', ...
    'autorouting', 'on');
add_line(ebsSystem, 'Bus Selector/2', 'EBS_Response_Monitor/3', ...
    'autorouting', 'on');
add_line(ebsSystem, 'Bus Selector1/1', 'EBS_Response_Monitor/4', ...
    'autorouting', 'on');
add_line(ebsSystem, 'Bus Selector1/2', 'EBS_Response_Monitor/5', ...
    'autorouting', 'on');

faultDelay = [ebsSystem '/EBS_Sensor_Fault_Delay'];
if getSimulinkBlockHandle(faultDelay) == -1
    add_block('simulink/Discrete/Unit Delay', faultDelay, ...
        'InitialCondition', 'false', 'SampleTime', '-1', ...
        'Position', [785 360 835 395]);
end
delete_input_line(faultDelay, 1);
add_line(ebsSystem, 'EBS_Response_Monitor/1', ...
    'EBS_Sensor_Fault_Delay/1', 'autorouting', 'on');

